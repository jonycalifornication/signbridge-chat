/**
 * Занимает ли задача место воркера.
 *
 * Отдельным файлом — чтобы это можно было проверить тестом: `index.js`
 * поднимает сервер прямо при импорте, и втащить его в юнит-тест нельзя.
 */

/**
 * Считается ли задача нашей текущей работой.
 *
 * Отданная соседу (`movedTo`) — НЕ считается. Запись о ней живёт дальше, но
 * только как переадресация: опрос статуса и скачивание приходят по прежнему
 * номеру задачи, а считает её уже сосед. Пока она числилась в работе, воркер
 * навсегда терял своё единственное место: отдал — и до перезапуска отвечает
 * соседям «занят».
 *
 * Чем это кончалось на боксе (замер 06.10.2026): из четырёх воркеров три
 * сообщали `free: false` при нулевой загрузке карт и ноле активных задач —
 * у каждого висела одна отданная. Свободных соседей не осталось, выбор карты
 * по занятости перестал работать, и вся очередь выстроилась за единственным
 * воркером, который ещё никому ничего не отдавал.
 */
export function countsAsInFlight(task) {
    if (!task || task.movedTo) return false;
    return task.status !== 'completed' && task.status !== 'error';
}

/** Сколько задач у нас в работе. */
export function tasksInFlight(tasks) {
    let n = 0;
    for (const task of tasks.values()) {
        if (countsAsInFlight(task)) n += 1;
    }
    return n;
}
